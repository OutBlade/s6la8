"""Generate the FPGA pin constraints from the schematic.

    python gen_pins.py            (run in hardware/, after `pcb apply schematic`)

Reads the KiCad netlist exported from eda/s6la8.kicad_sch and writes
../gateware/ise/pins.ucf, so the gateware can never disagree with the board
about which signal is on which FPGA pin.
"""
import glob
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BUSES = ("FD", "CH", "SD_DQ", "SD_A")          # names with a trailing index
SKIP = re.compile(r"^(GND|VCC_|unconnected-|M[01]$|INIT_B$|HSWAPEN$|CSI_B$|RDWR_B$|PROGRAM_B$|DONE$|T(CK|DI|DO|MS)$)")


def kicad_cli():
    found = sorted(glob.glob("C:/Program Files/KiCad/*/bin/kicad-cli.exe"), reverse=True)
    return found[0] if found else "kicad-cli"


def main():
    net = os.path.join(HERE, "out", "s6la8.net")
    os.makedirs(os.path.dirname(net), exist_ok=True)
    subprocess.run([kicad_cli(), "sch", "export", "netlist", "-o", net,
                    os.path.join(HERE, "eda", "s6la8.kicad_sch")], check=True, capture_output=True)
    text = open(net, encoding="utf-8").read()

    m = re.search(r'\(comp\s*\(ref "([^"]+)"\)\s*\(value "XC6SLX9[^"]*"\)', text)
    if not m:
        sys.exit("FPGA not found in netlist")
    fpga = m.group(1)

    pins = {}
    for name, body in re.findall(r'\(net\s*\(code "?\d+"?\)\s*\(name "([^"]*)"\)(.*?)(?=\(net\s*\(code|\Z)', text, re.S):
        name = name.lstrip("/")
        if SKIP.match(name):
            continue
        for pin in re.findall(r'\(node\s*\(ref "%s"\)\s*\(pin "(\d+)"\)' % re.escape(fpga), body):
            pins[name] = int(pin)

    lines = ["# Generated by hardware/gen_pins.py from the schematic. Do not edit.",
             'CONFIG VCCAUX = "3.3";', ""]
    for name in sorted(pins, key=lambda n: (re.sub(r"\d+$", "", n), int(re.search(r"(\d+)$", n).group(1)) if re.search(r"\d+$", n) else 0)):
        port = name
        bus = re.match(r"^(%s)(\d+)$" % "|".join(BUSES), name)
        if bus:
            port = "%s<%s>" % bus.groups()
        lines.append('NET "%s" LOC = P%d | IOSTANDARD = LVCMOS33;' % (port, pins[name]))
    out = os.path.join(HERE, "..", "gateware", "ise", "pins.ucf")
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%d FPGA pins written to gateware/ise/pins.ucf (FPGA is %s)" % (len(pins), fpga))


if __name__ == "__main__":
    main()
