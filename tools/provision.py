"""Factory provisioning for s6la8 board authentication.

    python tools/provision.py newkey  SECRET.key          # once: make the product key
    python tools/provision.py keyfile SECRET.key          # write gateware/rtl/auth_key.vh for ISE
    python tools/provision.py tag     SECRET.key DNA_HEX  # tag for one board
    python tools/provision.py selftest

The key must never be committed.  Keep SECRET.key offline (password manager,
encrypted USB stick) with a backup: without it no further boards can be
provisioned for the existing bitstream.

The gateware (rtl/dna_auth.v) computes SipHash-2-4(key, DNA) where DNA is the
57-bit Device DNA as a little-endian 64-bit word, and compares it with the
8-byte tag the FX2 copies from EEPROM offset 0x3F00 into FPGA registers
0x30..0x37.
"""
import os
import struct
import sys

MASK = (1 << 64) - 1
EEPROM_TAG_OFFSET = 0x3F00


def _rotl(x, b):
    return ((x << b) | (x >> (64 - b))) & MASK


def siphash24(key: bytes, msg: bytes) -> int:
    k0, k1 = struct.unpack("<QQ", key)
    v0, v1 = k0 ^ 0x736F6D6570736575, k1 ^ 0x646F72616E646F6D
    v2, v3 = k0 ^ 0x6C7967656E657261, k1 ^ 0x7465646279746573

    def rnd():
        nonlocal v0, v1, v2, v3
        v0 = (v0 + v1) & MASK; v1 = _rotl(v1, 13) ^ v0; v0 = _rotl(v0, 32)
        v2 = (v2 + v3) & MASK; v3 = _rotl(v3, 16) ^ v2
        v0 = (v0 + v3) & MASK; v3 = _rotl(v3, 21) ^ v0
        v2 = (v2 + v1) & MASK; v1 = _rotl(v1, 17) ^ v2; v2 = _rotl(v2, 32)

    n = len(msg)
    tail = msg[n - n % 8:] + b"\0" * (7 - n % 8) + bytes([n & 0xFF])
    for blk in [msg[i:i + 8] for i in range(0, n - n % 8, 8)] + [tail]:
        m = struct.unpack("<Q", blk)[0]
        v3 ^= m
        rnd(); rnd()
        v0 ^= m
    v2 ^= 0xFF
    for _ in range(4):
        rnd()
    return v0 ^ v1 ^ v2 ^ v3


def tag(key: bytes, dna: int) -> int:
    assert 0 <= dna < 1 << 57, "Device DNA is 57 bits"
    return siphash24(key, struct.pack("<Q", dna))


def load_key(path):
    key = bytes.fromhex(open(path).read().strip())
    assert len(key) == 16, "key must be 16 bytes"
    return key


def main(argv):
    cmd = argv[1] if len(argv) > 1 else "selftest"
    if cmd == "newkey":
        if os.path.exists(argv[2]):
            sys.exit("refusing to overwrite " + argv[2])
        with open(argv[2], "w") as f:
            f.write(os.urandom(16).hex() + "\n")
        print("new key written to", argv[2], "- back it up and keep it out of git")
    elif cmd == "keyfile":
        key = load_key(argv[2])
        k = int.from_bytes(key[8:], "little") << 64 | int.from_bytes(key[:8], "little")
        out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "gateware", "rtl", "auth_key.vh")
        with open(out, "w") as f:
            f.write("// Generated by tools/provision.py keyfile.  SECRET: never commit this file.\n")
            f.write("localparam [127:0] AUTH_KEY = 128'h%032x;\nlocalparam AUTH_REQUIRED = 1;\n" % k)
        print("wrote", os.path.normpath(out))
    elif cmd == "tag":
        t = tag(load_key(argv[2]), int(argv[3], 16))
        print("tag %016x" % t)
        print("EEPROM bytes at 0x%04x: %s" % (EEPROM_TAG_OFFSET, t.to_bytes(8, "little").hex(" ")))
    elif cmd == "selftest":
        # reference vector from the SipHash paper: key 00..0f, message 00..07
        assert siphash24(bytes(range(16)), bytes(range(8))) == 0x93F5F5799A932462
        print("siphash ok; sim vector: tag(key 00..0f, dna 0x123456789abcdef) = %016x"
              % tag(bytes(range(16)), 0x123456789ABCDEF))
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv)
